using System.Diagnostics;

namespace Tumbler.Gui;

public sealed record HelpStep(int Number, string Text);

public sealed record HelpQuestion(string Problem, string Fix);

/// <summary>Раздел справки: общий или про конкретный VPN-клиент.</summary>
public sealed class HelpTopic
{
    public required string Title { get; init; }
    public required string Intro { get; init; }
    public string? Port { get; init; }
    public IReadOnlyList<HelpStep> Steps { get; init; } = [];
    public IReadOnlyList<string> Notes { get; init; } = [];
    public IReadOnlyList<HelpQuestion> Questions { get; init; } = [];

    /// <summary>Имена процессов клиента — по ним справка сама открывает нужный раздел.</summary>
    public IReadOnlyList<string> Processes { get; init; } = [];

    public bool Running { get; set; }
    public bool HasPort => Port is not null;
    public bool HasSteps => Steps.Count > 0;
    public bool HasNotes => Notes.Count > 0;
}

